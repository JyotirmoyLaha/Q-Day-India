// Human-readable Markdown report.
import type { Finding, QuantumRisk, ScanReport } from '../types';
import { getFix } from '../rules';
import { assetName } from '../algorithms';

const HEADINGS: Record<QuantumRisk, string> = {
  HIGH: 'Not quantum-safe (Shor) — migration recommended',
  CLASSICAL_BROKEN: 'Already weak today — replace now',
  LOW: 'Weakened by Grover — increase key size',
  NONE: 'Informational',
};

const ORDER: QuantumRisk[] = ['HIGH', 'CLASSICAL_BROKEN', 'LOW', 'NONE'];

const fence = (code: string) => {
  const ticks = code.includes('```') ? '````' : '```';
  return `${ticks}\n${code}\n${ticks}`;
};

export function toMarkdown(report: ScanReport): string {
  const out: string[] = [];
  const date = report.scannedAt.slice(0, 10);
  out.push(`# QuantumBOM report — ${report.source.name}`);
  out.push('');
  out.push(
    `Scanned ${date} with ${report.tool.name} ${report.tool.version}. ${report.stats.filesScanned} files analysed, ${report.findings.length} findings.`,
  );
  out.push('');
  out.push('## Scores');
  out.push('');
  out.push(`| Score | Value |\n|---|---|\n| Quantum Exposure | **${report.scores.exposure}/100** |\n| Crypto-Agility | **${report.scores.agility}/100** |`);
  out.push('');
  out.push('<details><summary>Score inputs</summary>\n');
  for (const i of [...report.scores.exposureInputs, ...report.scores.agilityInputs]) out.push(`- ${i.label}: ${i.value}`);
  out.push('\n</details>');
  out.push('');

  out.push('## Summary');
  out.push('');
  out.push('| Risk | Findings |\n|---|---|');
  for (const r of ORDER) out.push(`| ${HEADINGS[r]} | ${report.findings.filter((f) => f.quantumRisk === r).length} |`);
  out.push('');

  const fixIds = new Set<string>();
  for (const r of ORDER) {
    const fs = report.findings.filter((f) => f.quantumRisk === r);
    if (!fs.length) continue;
    out.push(`## ${HEADINGS[r]}`);
    out.push('');
    const byFile = new Map<string, Finding[]>();
    for (const f of fs) byFile.set(f.file, [...(byFile.get(f.file) ?? []), f]);
    for (const [file, list] of byFile) {
      out.push(`### \`${file}\``);
      out.push('');
      for (const f of list) {
        const fix = getFix(f.fixId);
        if (fix) fixIds.add(fix.id);
        out.push(`- **Line ${f.line}** — ${assetName(f)} (${f.primitive}, confidence ${f.confidence}): ${f.message}${fix ? ` Fix: [${fix.title}](#fix-${fix.id})` : ''}`);
        out.push('');
        out.push(fence(f.snippet).replace(/^/gm, '  '));
        out.push('');
      }
    }
  }

  if (fixIds.size) {
    out.push('## Fixes');
    out.push('');
    for (const id of fixIds) {
      const fix = getFix(id)!;
      out.push(`### <a id="fix-${fix.id}"></a>${fix.title}`);
      out.push('');
      out.push(`_Last verified ${fix.verified}._`);
      out.push('');
      out.push(fix.markdown.trim());
      out.push('');
    }
  }

  if (report.warnings.length) {
    out.push('## Warnings');
    out.push('');
    for (const w of report.warnings) out.push(`- ${w}`);
    out.push('');
  }
  out.push('---');
  out.push('Static analysis has false positives and misses algorithms chosen at runtime; confidence levels are shown per finding. Generated by Q-Day India QuantumBOM — the code never left the machine it was scanned on.');
  return out.join('\n') + '\n';
}
